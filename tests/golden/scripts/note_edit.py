#!/usr/bin/env python3
"""What may be edited in place, and whether the editor still has the file it read.

The MCP server can create a note (`add_note`) and now change one (`replace_note`). Everything
an edit must decide *before* touching the disk lives here rather than in `mcp_server.py`, for
one practical reason: that module imports the MCP SDK, which is an **optional** dependency, so
CI cannot import it and the MCP test tier runs by hand. A tier that runs by hand drifts — it
has, twice. This module imports nothing optional, so the rules below are gated on every commit.

Two decisions, and the first one is easy to get wrong.

**The concurrency token is a WHOLE-FILE digest, not ``note_view.content_hash``.**
``content_hash`` is taken over the *canonical view*, which deliberately strips ``no-embed`` and
``lexical-only`` regions — that is what makes editing inside a fence free of re-embedding. It is
therefore **blind** to a change inside a fence. Tick a checkbox in a ``lexical-only`` block and
the content hash is unchanged. Used as an edit token it would let a client overwrite that
checkbox and report success, which is the exact failure the token exists to prevent. So the
token is sha256 over the file's bytes, frontmatter and fences included.

**What may be edited is an allow-list, not a deny-list.** Markdown notes under the four PARA
roots, plus a small set of files at the vault root. The glossary is excluded on purpose: it has
its own writer (``add_glossary_term``) that cascades links across the vault, and a raw edit
would bypass that cascade and leave the link graph stale.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

PARA_ROOTS = ("projects", "areas", "resources", "archive")

# Editable files that sit at the vault ROOT rather than under a PARA root. Both hold state the
# owner maintains by hand, which is why an assistant is allowed to change them at all.
#
# NOT advertised. `replace_note`'s docstring describes PARA notes and stops there, and a refusal
# names only what was refused — a docstring enumerating this list would announce the dashboard
# to every client, which is the opposite of the intent. A client reaches them by already knowing
# the path, via `get_note("vault/dashboard-index.md")`.
VAULT_ROOT_EDITABLE = ("dashboard-index.md", "inbox.md")


class NotEditable(ValueError):
    """The target is outside what an in-place edit is allowed to touch."""


def file_hash(path: Path) -> str:
    """The edit token: sha256 over the file's bytes.

    Deliberately **not** ``note_view.content_hash`` — see the module docstring. Reads bytes
    rather than text so a CRLF file hashes as what is actually stored, and the comparison can
    never be thrown off by newline translation on the way in.
    """
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def resolve_editable(source_file: str, brain: Path) -> Path:
    """Resolve ``source_file`` to a file an edit may replace, or raise ``NotEditable``.

    Accepts an absolute path (as a search hit returns) or a brain-relative one. Resolves first
    and compares the *resolved* path against the vault, so a symlink or a ``..`` segment cannot
    smuggle a target in — the check is on where the path lands, not on how it is spelled.

    Existence is checked by the caller, not here: "does not exist" and "is not editable" are
    different answers and deserve different messages.
    """
    vault = (brain / "vault").resolve()
    p = Path(source_file)
    if not p.is_absolute():
        p = brain / source_file
    p = p.resolve()

    if vault not in p.parents:
        raise NotEditable(f"refusing to edit outside the vault: {source_file}")
    if p.suffix != ".md":
        raise NotEditable(
            f"only Markdown notes can be edited, not {p.name} — an asset is written once by "
            f"add_asset and replaced by hand")
    if p.name.startswith("."):
        raise NotEditable(f"{p.name} is a derived sidecar, not a note — it is regenerated by "
                          f"the embed hook and must never be hand-edited")

    rel = p.relative_to(vault)
    parts = rel.parts
    if len(parts) == 1:
        if rel.name in VAULT_ROOT_EDITABLE:
            return p
        raise NotEditable(f"{rel.as_posix()} is not an editable note")
    if parts[0] in PARA_ROOTS:
        return p
    if parts[0] == "glossary":
        raise NotEditable(
            "glossary terms are not edited in place: add_glossary_term cascades the term's "
            "links across the vault, and a raw edit would leave that graph stale. Edit the "
            "term note in your editor, or add a new term with add_glossary_term.")
    raise NotEditable(
        f"vault/{parts[0]}/ is not a PARA root, so nothing in it is an editable note "
        f"(editable: {', '.join(PARA_ROOTS)})")
